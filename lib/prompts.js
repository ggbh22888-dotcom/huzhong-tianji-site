const LANG_NAMES = { en: "English", "zh-CN": "简体中文", "zh-TW": "繁體中文", ja: "日本語", ko: "한국어", ru: "русский", es: "español", th: "ภาษาไทย", vi: "tiếng Việt", km: "ភាសាខ្មែរ", lo: "ພາສາລາວ", pt: "português" };
function langRule(lang) {
  if (!lang || lang === "zh-CN") return "";
  if (lang === "zh-TW") return "\n\n【输出语言】全文使用繁體中文（台灣/港澳慣用字），品牌名與結尾固定句照舊。";
  const n = LANG_NAMES[lang] || lang;
  return `\n\n【输出语言】全文使用 ${n} 书写，包括所有 ## 小标题。命理术语（如天干地支、十神、卦名、星曜）第一次出现时保留中文原文并在括号内给出 ${n} 的释义，之后可只用 ${n}。品牌名「壺中天機」保留中文。最后一行固定句改为：「命由己造，相由心生。」的 ${n} 译文，后接「壺中天機」。`;
}
function buildSystemPrompt(mode, lang) {
  const m = MODES[mode] || MODES.single;
  return `${VOICE}\n\n【本次任务：${m.title}】\n${m.structure}${langRule(lang)}`;
}

