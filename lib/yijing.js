const YAO_NAMES = ["初", "二", "三", "四", "五", "上"];

function hexFromBits(bits /* array of 0/1 bottom→top */) {
  const lower = TRIGRAMS[bits.slice(0, 3).join("")], upper = TRIGRAMS[bits.slice(3, 6).join("")];
  const [number, name, text] = HEX[upper.name + lower.name];
  return { number, name, text, upper, lower, bits };
}

/** values: six numbers in {6,7,8,9}, bottom→top */
function castFromValues(values) {
  if (!Array.isArray(values) || values.length !== 6 || values.some((v) => ![6, 7, 8, 9].includes(v))) throw new Error("需要六个爻值（6/7/8/9）");
  const bits = values.map((v) => (v % 2 === 1 ? 1 : 0));          // 7,9 阳；6,8 阴
  const changing = values.map((v, i) => (v === 6 || v === 9 ? i : -1)).filter((i) => i >= 0);
  const ben = hexFromBits(bits);
  const zhiBits = bits.map((b, i) => (changing.includes(i) ? 1 - b : b));
  const zhi = changing.length ? hexFromBits(zhiBits) : null;
  const lines = values.map((v, i) => ({
    position: i + 1,
    label: (bits[i] ? (i === 0 ? "初九" : i === 5 ? "上九" : `九${YAO_NAMES[i]}`) : (i === 0 ? "初六" : i === 5 ? "上六" : `六${YAO_NAMES[i]}`)),
    value: v, yinYang: bits[i] ? "阳" : "阴", changing: changing.includes(i),
    coins: v === 6 ? "三字" : v === 9 ? "三背" : v === 7 ? "一背二字" : "二背一字",
  }));
  // 互卦 (2-3-4 下, 3-4-5 上)
  const hu = hexFromBits([bits[1], bits[2], bits[3], bits[2], bits[3], bits[4]]);
  // 解卦规则（朱熹法）提示
  let rule;
  switch (changing.length) {
    case 0: rule = "无变爻：以本卦卦辞为断。"; break;
    case 1: rule = `一爻变：以本卦变爻（${lines[changing[0]].label}）爻辞为断。`; break;
    case 2: rule = `二爻变：以本卦两变爻爻辞为断，以上爻（${lines[changing[1]].label}）为主。`; break;
    case 3: rule = "三爻变：以本卦与之卦卦辞合断，本卦为贞（现状），之卦为悔（走向）。"; break;
    case 4: rule = `四爻变：以之卦两不变爻爻辞为断，以下爻为主。`; break;
    case 5: rule = "五爻变：以之卦不变之爻的爻辞为断。"; break;
    default: rule = ben.number === 1 ? "六爻皆变：乾之坤，以用九为断。" : ben.number === 2 ? "六爻皆变：坤之乾，以用六为断。" : "六爻皆变：以之卦卦辞为断。";
  }
  return { system: "易经·金钱卦", lines, ben, zhi, hu, changing: changing.map((i) => i + 1), rule };
}

/** server-side random cast (if client does not animate) */
function castRandom() {
  const { randomInt } = require("crypto");
  const values = Array.from({ length: 6 }, () => randomInt(2, 4) + randomInt(2, 4) + randomInt(2, 4));
  return castFromValues(values);
}

